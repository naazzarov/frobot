import { templateResult } from "./core.js";
import { ledgerReport, summarizeLedger } from "./finance.js";
export const STAGES = [
  { id: "executive", label: "Executive plan", role: "Executive" },
  { id: "manager", label: "Manager breakdown", role: "Manager" },
  { id: "specialist", label: "Specialist deliverable", role: "Specialist" },
  { id: "reviewer", label: "Independent review", role: "Reviewer" },
];
const bounded = (v, n) =>
  typeof v === "string" && v.trim().length > 0 && v.length <= n;
export function validateStage(stage, value, context) {
  if (!value || typeof value !== "object" || Array.isArray(value))
    throw Error("Stage must return a structured object.");
  const list = (v, n = 8) =>
    Array.isArray(v) && v.length <= n && v.every((s) => bounded(s, 1600));
  if (
    stage === "executive" &&
    (!bounded(value.objective, 2000) ||
      !list(value.acceptance) ||
      !value.acceptance.length ||
      !list(value.risks))
  )
    throw Error("Invalid executive plan.");
  if (
    stage === "manager" &&
    (!list(value.steps, 5) ||
      !value.steps.length ||
      !list(value.definitionOfDone) ||
      !value.definitionOfDone.length)
  )
    throw Error("Invalid manager plan.");
  if (stage === "specialist") {
    if (!bounded(value.artifact, 14000) || !list(value.evidenceIds, 1000))
      throw Error("Invalid specialist result.");
    if (/<[a-z][^>]*>|!\[/i.test(value.artifact))
      throw Error(
        "Deliverables must not contain raw HTML or embedded remote images.",
      );
    const allowed = new Set([
      ...(context.finance?.rows.map((r) => r.id) || []),
      ...context.knowledge.map((k) => k.id).filter(Boolean),
    ]);
    if (value.evidenceIds.some((id) => !allowed.has(id)))
      throw Error("Result cites evidence outside its company context.");
    if (context.finance && !value.evidenceIds.length)
      throw Error("A source-backed result must cite its source rows.");
    if (context.finance && /[0-9$€£¥]/.test(value.artifact))
      throw Error(
        "Finance commentary must not introduce numerical claims. Figures belong in the calculated source report; citations belong in evidenceIds.",
      );
  }
  if (
    stage === "reviewer" &&
    (typeof value.passed !== "boolean" ||
      !list(value.issues) ||
      !bounded(value.summary, 2000) ||
      (value.passed && value.issues.length))
  )
    throw Error("Invalid review result.");
  return value;
}
export function deterministicStage(stage, context, outputs) {
  if (stage === "executive")
    return {
      objective: context.task.title,
      acceptance: [
        "Address the Owner directive.",
        "Keep calculations tied to immutable source rows.",
        "Deliver a draft with explicit assumptions and execution limits.",
      ],
      risks: context.finance
        ? ["Cash movement is not profit or a reconciled closing balance."]
        : ["No external sources or external tools are available."],
    };
  if (stage === "manager")
    return {
      steps: [
        "Inspect company-scoped evidence and source quality flags.",
        "Prepare the requested deliverable.",
        "Check citations, calculations, and approval boundaries.",
      ],
      definitionOfDone: outputs.executive.acceptance,
    };
  if (stage === "specialist")
    return {
      artifact: context.finance
        ? `## CFO interpretation checklist\n\nThe verified report was computed from the source, not generated by a model. Review uncategorized rows and duplicate flags with the Owner. Set a target only after validating source completeness. No financial transaction was performed.`
        : templateResult({
            ...context,
            knowledge: context.knowledge.slice(0, 8),
          }),
      evidenceIds: context.finance
        ? context.finance.rows.map((r) => r.id)
        : context.knowledge.map((k) => k.id).filter(Boolean),
    };
  return {
    passed: true,
    issues: [],
    summary: context.finance
      ? "All reported figures are produced by the deterministic ledger calculator; cited row IDs exist in the selected company source. Accounting accuracy and source completeness still require Owner review."
      : "The planning template is structured, company-scoped, and does not execute external actions. No model quality judgment is implied.",
  };
}
export async function executeWorkflow(
  context,
  provider,
  { checkpoint = async () => {}, reserve = async () => {}, signal } = {},
) {
  context = structuredClone(context);
  const outputs = {},
    trace = [];
  for (const stage of STAGES) {
    signal?.throwIfAborted();
    await reserve(stage);
    const startedAt = new Date().toISOString();
    const response = provider?.generateStage
      ? await provider.generateStage(
          stage.id,
          structuredClone(context),
          structuredClone(outputs),
          signal,
        )
      : deterministicStage(stage.id, context, outputs);
    signal?.throwIfAborted();
    const value = validateStage(stage.id, response.value || response, context);
    outputs[stage.id] = value;
    const entry = {
      stage: stage.id,
      label: stage.label,
      role: stage.role,
      status: "complete",
      startedAt,
      completedAt: new Date().toISOString(),
      output: value,
      provider: provider?.name || "deterministic",
      usage: response.usage || null,
    };
    trace.push(entry);
    await checkpoint(entry);
    if (stage.id === "reviewer" && !value.passed)
      throw Error(
        "The reviewer requested changes. Inspect the stage trace before retrying.",
      );
  }
  const report = context.finance ? ledgerReport(context.finance) : "";
  const artifact = `${report ? report + "\n\n## Advisory commentary\n" : ""}${outputs.specialist.artifact}\n\n## Workflow review\n${outputs.reviewer.summary}\n\n${provider?.name === "anthropic" ? "Planning, decomposition, drafting, and review used separate bounded model calls. The review is advisory, not a guarantee of correctness." : "Four deterministic workflow stages were executed. No AI request was made."}`;
  if (artifact.length > 30000)
    throw Error(
      "Deliverable exceeds the artifact size limit. Use a smaller source.",
    );
  return {
    artifact,
    trace,
    verification: context.finance ? summarizeLedger(context.finance) : null,
  };
}
